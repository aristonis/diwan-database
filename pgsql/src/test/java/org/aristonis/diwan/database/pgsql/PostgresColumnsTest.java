package org.aristonis.diwan.database.pgsql;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.Arrays;
import java.util.List;
import org.aristonis.diwan.database.Connection;
import org.aristonis.diwan.database.schema.ColumnInfo;
import org.aristonis.diwan.database.schema.Schema;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.postgresql.ds.PGSimpleDataSource;

/** Reading column details on PostgreSQL. */
class PostgresColumnsTest {

    private Connection db;
    private Schema schema;

    @BeforeEach
    void createDatabase() {
        db = PostgresServer.newDatabase();
        schema = PostgresSchema.of(db);
    }

    private ColumnInfo column(String table, String name) {
        for (ColumnInfo info : schema.getColumns(table)) {
            if (info.name().equals(name)) {
                return info;
            }
        }
        throw new AssertionError("no column " + name);
    }

    @Test
    void varcharNotNullWithDefaultReportsTypeNameAndDefaultText() {
        db.statement("create table t (name varchar(255) not null default 'x')");

        ColumnInfo info = column("t", "name");

        assertEquals("character varying(255)", info.type());
        assertEquals("varchar", info.typeName());
        assertFalse(info.isNullable());
        assertEquals("'x'::character varying", info.defaultValue().orElseThrow());
        assertFalse(info.isAutoIncrement());
        assertFalse(info.generation().isPresent());
    }

    @Test
    void nullableIntHasNoDefaultCollationOrComment() {
        db.statement("create table t (n int)");

        ColumnInfo info = column("t", "n");

        assertTrue(info.isNullable());
        assertEquals("integer", info.type());
        assertEquals("int4", info.typeName());
        assertFalse(info.defaultValue().isPresent());
        assertFalse(info.collation().isPresent());
        assertFalse(info.comment().isPresent());
    }

    @Test
    void collatedTextReportsTheCollation() {
        db.statement("create table t (a text collate \"C\", b text)");

        assertEquals("C", column("t", "a").collation().orElseThrow());
        assertFalse(column("t", "b").collation().isPresent());
    }

    @Test
    void unknownTableGivesAnEmptyList() {
        assertTrue(schema.getColumns("nope").isEmpty());
    }

    @Test
    void serialAndIdentityColumnsAreAutoIncrement() {
        db.statement("create table t (s serial, g int generated always as identity,"
                + " d int generated by default as identity, plain int)");

        assertTrue(column("t", "s").isAutoIncrement());
        assertTrue(column("t", "s").defaultValue().orElseThrow().startsWith("nextval("));
        assertTrue(column("t", "g").isAutoIncrement());
        assertFalse(column("t", "g").defaultValue().isPresent());
        assertTrue(column("t", "d").isAutoIncrement());
        assertFalse(column("t", "plain").isAutoIncrement());
    }

    @Test
    void storedGeneratedColumnHasTheExpressionAndNoDefault() {
        db.statement("create table t (a int, b int generated always as (a * 2) stored)");

        ColumnInfo info = column("t", "b");

        assertTrue(info.generation().orElseThrow().isStored());
        assertEquals("(a * 2)", info.generation().orElseThrow().expression());
        assertFalse(info.defaultValue().isPresent());
        assertFalse(column("t", "a").generation().isPresent());
    }

    @Test
    void droppedColumnIsNotListed() {
        db.statement("create table t (a int, b int, c int)");
        db.statement("alter table t drop column b");

        assertEquals(Arrays.asList("a", "c"), schema.getColumnListing("t"));
    }

    @Test
    void columnCommentIsReported() {
        db.statement("create table t (a int, b int)");
        db.statement("comment on column t.a is 'the a'");

        assertEquals("the a", column("t", "a").comment().orElseThrow());
        assertFalse(column("t", "b").comment().isPresent());
    }

    @Test
    void viewColumnsAreListedInOrder() {
        db.statement("create table t (a int, b text)");
        db.statement("create view v as select b, a from t");

        List<ColumnInfo> columns = schema.getColumns("v");

        assertEquals(Arrays.asList("b", "a"), schema.getColumnListing("v"));
        assertEquals("text", columns.get(0).type());
    }

    @Test
    void arrayColumnTypeNameIsTheInternalArrayName() {
        db.statement("create table t (a int[])");

        assertEquals("_int4", column("t", "a").typeName());
        assertEquals("integer[]", column("t", "a").type());
    }

    @Test
    void domainColumnReportsTheDomainName() {
        db.statement("create domain posint as int check (value > 0)");
        db.statement("create table t (a posint)");

        assertEquals("posint", column("t", "a").typeName());
        assertEquals("posint", column("t", "a").type());
    }

    @Test
    void twoSchemasWithTheSameTableReadTheCurrentSchemaOnly() {
        db.statement("create schema extra");
        PGSimpleDataSource source = PostgresServer.dataSource(
                String.valueOf(db.scalar("select current_database()").orElseThrow()));
        source.setCurrentSchema("extra,public");
        Connection both = Connection.builder().name("pgsql").dataSource(source).build();
        both.statement("create table public.users (id int, legacy text)");
        both.statement("create table extra.users (id int, email text)");

        assertEquals(Arrays.asList("id", "email"), PostgresSchema.of(both).getColumnListing("users"));
    }
}
