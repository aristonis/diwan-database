package org.aristonis.diwan.database.pgsql;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.util.List;
import java.util.Map;
import org.aristonis.diwan.database.Connection;
import org.aristonis.diwan.database.exception.QueryException;
import org.aristonis.diwan.database.query.QueryFactory;
import org.aristonis.diwan.database.schema.DatabaseVersion;
import org.junit.jupiter.api.Test;

class PostgresRestartIdentitiesTest {

    private static final int PARTITIONED_IDENTITY_SINCE = 17;

    private static long nextId(QueryFactory db, String table) {
        return ((Number) db.table(table).insertGetId(Map.of("label", "x"))).longValue();
    }

    private static void insertAndRollBack(Connection connection, String table, int rows) {
        assertThrows(IllegalStateException.class, () -> connection.transaction(tx -> {
            for (int i = 0; i < rows; i++) {
                PostgresQuery.of(tx).table(table).insert(Map.of("label", "x"));
            }
            throw new IllegalStateException("roll back");
        }));
    }

    @Test
    void identityAndSerialInOneTableBothStartOverAfterARollback() {
        Connection connection = PostgresServer.newDatabase();
        connection.statement("create table t (id integer generated by default as identity primary key,"
                + " n serial, label text)");
        QueryFactory db = PostgresQuery.of(connection);
        insertAndRollBack(connection, "t", 3);

        db.restartIdentities(List.of("t"));

        db.table("t").insert(Map.of("label", "a"));
        assertEquals(Map.of("id", 1, "n", 1), idsOf(db));
    }

    private static Map<String, Object> idsOf(QueryFactory db) {
        Map<String, Object> row = db.table("t").first().orElseThrow(IllegalStateException::new);
        return Map.of("id", row.get("id"), "n", row.get("n"));
    }

    @Test
    void aSequenceThatStartsAt100RestartsAt100() {
        Connection connection = PostgresServer.newDatabase();
        connection.statement("create table t (id bigint generated by default as identity (start with 100)"
                + " primary key, label text)");
        QueryFactory db = PostgresQuery.of(connection);
        insertAndRollBack(connection, "t", 2);

        db.restartIdentities(List.of("t"));

        assertEquals(100L, nextId(db, "t"));
    }

    @Test
    void seededCommittedRowsAreContinuedNotOverwritten() {
        Connection connection = PostgresServer.newDatabase();
        connection.statement("create table t (id serial primary key, label text)");
        QueryFactory db = PostgresQuery.of(connection);
        connection.statement("insert into t (id, label) values (1, 'a'), (2, 'b'), (7, 'c')");

        db.restartIdentities(List.of("t"));

        assertEquals(8L, nextId(db, "t"));
    }

    @Test
    void aDescendingSequenceContinuesBelowTheLowestValue() {
        Connection connection = PostgresServer.newDatabase();
        connection.statement("create table t (id bigint generated by default as identity"
                + " (increment by -1 start with -1 minvalue -1000 maxvalue -1) primary key, label text)");
        QueryFactory db = PostgresQuery.of(connection);
        assertEquals(-1L, nextId(db, "t"));
        assertEquals(-2L, nextId(db, "t"));
        assertEquals(-3L, nextId(db, "t"));

        db.restartIdentities(List.of("t"));

        assertEquals(-4L, nextId(db, "t"));

        db.table("t").delete();
        db.restartIdentities(List.of("t"));

        assertEquals(-1L, nextId(db, "t"));
    }

    @Test
    void aMixedCaseTableNameIsFoundByItsQuotedName() {
        Connection connection = PostgresServer.newDatabase();
        connection.statement("create table \"Users\" (id serial primary key, label text)");
        QueryFactory db = PostgresQuery.of(connection);
        insertAndRollBack(connection, "Users", 2);

        db.restartIdentities(List.of("Users"));

        assertEquals(1L, nextId(db, "Users"));
    }

    @Test
    void aTableInAnotherSchemaWithAPrefixIsRestarted() {
        String database = PostgresServer.newDatabaseName();
        Connection connection = Connection.builder().name("pgsql").dataSource(PostgresServer.dataSource(database))
                .tablePrefix("app_").build();
        connection.statement("create schema shop");
        connection.statement("create table shop.app_orders (id serial primary key, label text)");
        QueryFactory db = PostgresQuery.of(connection);
        insertAndRollBack(connection, "shop.orders", 3);

        db.restartIdentities(List.of("shop.orders"));

        assertEquals(1L, nextId(db, "shop.orders"));
    }

    @Test
    void aPartitionedParentWithASerialColumnIsRestarted() {
        Connection connection = PostgresServer.newDatabase();
        connection.statement("create table t (id serial, label text) partition by range (id)");
        connection.statement("create table t_all partition of t for values from (1) to (1000000)");
        QueryFactory db = PostgresQuery.of(connection);
        insertAndRollBack(connection, "t", 3);

        db.restartIdentities(List.of("t"));

        assertEquals(1L, nextId(db, "t"));
    }

    @Test
    void aPartitionedParentWithAnIdentityColumnIsRestarted() {
        Connection connection = PostgresServer.newDatabase();
        String version = connection.scalar("show server_version").map(Object::toString).orElse("0");
        assumeTrue(DatabaseVersion.atLeast(version, PARTITIONED_IDENTITY_SINCE),
                "identity columns on partitioned tables need PostgreSQL 17");
        connection.statement("create table t (id integer generated by default as identity, label text)"
                + " partition by range (id)");
        connection.statement("create table t_all partition of t for values from (1) to (1000000)");
        QueryFactory db = PostgresQuery.of(connection);
        insertAndRollBack(connection, "t", 3);

        db.restartIdentities(List.of("t"));

        assertEquals(1L, nextId(db, "t"));
    }

    @Test
    void aTableWithoutASequenceIsAcceptedAndKeepsItsRows() {
        Connection connection = PostgresServer.newDatabase();
        connection.statement("create table plain (code text primary key)");
        QueryFactory db = PostgresQuery.of(connection);
        db.table("plain").insert(Map.of("code", "a"));

        db.restartIdentities(List.of("plain"));

        assertEquals(1L, db.table("plain").count());
    }

    @Test
    void aFreeSequenceUsedAsADefaultIsLeftUntouched() {
        Connection connection = PostgresServer.newDatabase();
        connection.statement("create sequence free_seq");
        connection.statement("create table t (id bigint primary key default nextval('free_seq'), label text)");
        QueryFactory db = PostgresQuery.of(connection);
        assertEquals(1L, nextId(db, "t"));
        assertEquals(2L, nextId(db, "t"));
        db.table("t").delete();

        db.restartIdentities(List.of("t"));

        assertEquals(3L, nextId(db, "t"));
    }

    @Test
    void aMissingTableFailsWithAQueryException() {
        QueryFactory db = PostgresQuery.of(PostgresServer.newDatabase());

        assertThrows(QueryException.class, () -> db.restartIdentities(List.of("nowhere")));
    }

    @Test
    void theResetStaysWhenTheEnclosingTransactionRollsBack() {
        Connection connection = PostgresServer.newDatabase();
        connection.statement("create table t (id serial primary key, label text)");
        QueryFactory db = PostgresQuery.of(connection);
        insertAndRollBack(connection, "t", 3);

        assertThrows(IllegalStateException.class, () -> connection.transaction(tx -> {
            PostgresQuery.of(tx).restartIdentities(List.of("t"));
            throw new IllegalStateException("roll back");
        }));

        assertEquals(1L, nextId(db, "t"));
    }
}
