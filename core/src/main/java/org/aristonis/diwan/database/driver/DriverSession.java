package org.aristonis.diwan.database.driver;

import org.aristonis.diwan.database.exception.DriverException;
import java.util.List;
import java.util.Map;
import java.util.OptionalInt;
import org.aristonis.diwan.database.Internal;

/**
 * Runs statements and transaction commands on one physical connection.
 *
 * <p>A session is not thread-safe and is used by one thread at a time. Handing a session to another
 * thread needs a happens-before handoff, for example through an executor or a concurrent queue.
 * Operations added in later versions arrive as {@code default} methods that throw
 * {@link UnsupportedOperationException}, so an existing driver keeps compiling.
 *
 * <p>Bound and returned values follow the values contract described in the
 * {@linkplain org.aristonis.diwan.database.driver package documentation}.
 *
 * <p>Savepoint names passed to {@link #savepoint(String)}, {@link #rollbackToSavepoint(String)}
 * and {@link #releaseSavepoint(String)} are generated by the core (as {@code diwan_N}, or
 * {@code diwan_N_M} for a later savepoint at the same depth N) and always
 * match {@code [A-Za-z_][A-Za-z0-9_]{0,29}}, so a driver may put them into SQL unquoted. Names are
 * unique within a session.
 *
 * @implSpec Implementations must report every failure as a {@link DriverException} whose kinds the
 *     driver sets, since only the driver knows its database's codes. Returned values must follow
 *     the values contract and be fully converted before the statement call returns. After any failed
 *     statement the session must stay usable, subject to the database's own rules (PostgreSQL, for
 *     example, aborts the surrounding transaction).
 * @apiNote Internal: driver SPI for dialect modules.
 */
@Internal
public interface DriverSession extends AutoCloseable {

    /**
     * Runs a read and returns its rows.
     *
     * @implSpec Rows must be in result order and each row's columns in select order, keyed by the
     *     label exactly as the database reports it. A label that appears twice in one result must
     *     fail with a {@link DriverException} with no kinds whose message names the label. The
     *     returned list and maps may be mutable; the core wraps them before handing them on.
     * @param sql the statement to run, never {@code null}
     * @param bindings the positional parameter values, never {@code null}, elements may be
     *     {@code null}; read-only to the driver and not retained
     * @return the rows in result order, never {@code null}, possibly empty
     * @throws DriverException if the statement fails or a column label appears twice in the result
     */
    List<Map<String, Object>> query(String sql, List<Object> bindings);

    /**
     * Runs a read and streams its rows through a cursor that keeps the statement open.
     *
     * <p>The session is busy until the cursor is closed: the core sends nothing else to it while
     * the cursor is open.
     *
     * @implSpec The default throws {@link UnsupportedOperationException}, for drivers written before
     *     cursors. Rows follow the rules of {@link #query}. A driver whose database streams only inside
     *     a transaction reports {@link DriverCapability#STREAMS_IN_TRANSACTION}; when no transaction
     *     is open and {@link #inExternalTransaction()} is {@code false}, it opens one for the cursor
     *     and ends it when the cursor closes (commit, or rollback after a failure), restoring the
     *     session as it was. Inside a transaction the cursor reads in it and never ends it. If opening
     *     fails, everything opened so far is released before the failure is thrown.
     * @param sql the statement to run, never {@code null}
     * @param bindings the positional parameter values, never {@code null}, elements may be
     *     {@code null}; read-only to the driver and not retained
     * @return the open cursor, never {@code null}
     * @throws DriverException if the statement fails or a column label appears twice in the result
     * @throws UnsupportedOperationException if the driver cannot stream
     */
    default RowCursor cursor(String sql, List<Object> bindings) {
        throw new UnsupportedOperationException("this driver cannot stream rows through a cursor");
    }

    /**
     * Runs a write and returns the number of affected rows.
     *
     * @param sql the statement to run, never {@code null}
     * @param bindings the positional parameter values, never {@code null}, elements may be
     *     {@code null}; read-only to the driver and not retained
     * @return the number of affected rows
     * @throws DriverException if the statement fails
     */
    int update(String sql, List<Object> bindings);

    /**
     * Runs any statement.
     *
     * @param sql the statement to run, never {@code null}
     * @param bindings the positional parameter values, never {@code null}, elements may be
     *     {@code null}; read-only to the driver and not retained
     * @return {@code true} if the statement produced a result set
     * @throws DriverException if the statement fails
     */
    boolean execute(String sql, List<Object> bindings);

    /**
     * Runs SQL without preparing it or binding parameters.
     *
     * @param sql the SQL to run, never {@code null}
     * @throws DriverException if the SQL fails
     */
    void executeUnprepared(String sql);

    /**
     * Tells whether the connection was already inside a transaction Diwan Database does not own.
     *
     * @implSpec The answer describes the connection as it was acquired, before any {@link #begin()}
     *     on this session, and must stay the same for the life of the session. When it is
     *     {@code true} the core never calls {@link #begin()}, {@link #commit()} or
     *     {@link #rollback()} on this session, only the savepoint methods; a driver may throw
     *     {@link IllegalStateException} if they are called anyway.
     * @return {@code true} if an external transaction was active when the connection was acquired
     * @throws DriverException if the state cannot be read
     */
    boolean inExternalTransaction();

    /**
     * Starts a transaction.
     *
     * @implSpec The connection stays inside the transaction until {@link #commit()},
     *     {@link #rollback()} or {@link #close()}. After {@code commit} or {@code rollback} the
     *     session may begin again.
     * @throws DriverException if the transaction cannot be started
     * @throws IllegalStateException if {@link #inExternalTransaction()} is {@code true}; optional
     */
    void begin();

    /**
     * Prepares a lock wait for the next transaction of this session.
     *
     * @implSpec The default throws {@link UnsupportedOperationException}, for drivers written before
     *     lock waits. The returned guard is used for one transaction: the core calls its steps around
     *     {@link #begin()} and then {@link LockWaitGuard#restore()}.
     * @param millis the longest wait in milliseconds, more than zero
     * @return the guard that applies and removes the wait, never {@code null}
     * @throws UnsupportedOperationException if the driver cannot limit the wait for a lock
     */
    default LockWaitGuard lockWait(long millis) {
        throw new UnsupportedOperationException("Lock wait is not supported by this driver");
    }

    /**
     * Prepares a limit on the wait for the locks of one statement, inside the open transaction. The
     * limit applies to that statement only. The core calls {@link LockWaitGuard#beforeBegin()} on the
     * guard to apply it, runs the statement, and calls {@link LockWaitGuard#restore()} to put the
     * previous wait back, unless the statement failed. {@link LockWaitGuard#afterBegin()} is not
     * used. Nothing is applied before {@code beforeBegin}.
     *
     * @implSpec The default throws {@link UnsupportedOperationException}, for drivers written before
     *     lock waits. A guard must not restore after a failed statement, because the database may
     *     have aborted the transaction; ending the transaction takes the limit back.
     * @param millis the longest wait in milliseconds, more than zero
     * @return the guard of that one statement, never {@code null}
     * @throws UnsupportedOperationException if the driver cannot limit the wait for a lock
     */
    default LockWaitGuard statementLockWait(long millis) {
        throw new UnsupportedOperationException("Lock wait is not supported by this driver");
    }

    /**
     * Tells how many significant digits the database keeps exactly in a decimal column.
     *
     * @implSpec The default returns empty, meaning the database keeps every digit its column type
     *     allows. A database that stores decimals as binary floating point returns the digits it keeps
     *     (SQLite: 15).
     * @return the number of exact significant digits, or empty when there is no such limit
     */
    default OptionalInt exactDecimalDigits() {
        return OptionalInt.empty();
    }

    /**
     * Commits the transaction {@link #begin()} started.
     *
     * <p>The core never retries a transaction whose commit failed, because the commit may have
     * landed before the failure was reported.
     *
     * @implSpec After this call the session may {@link #begin()} again. A driver must not classify a
     *     failure whose outcome is unknown, such as a connection lost during the commit, as
     *     {@link DriverFailureKind#CONCURRENCY}; only a commit the database definitely refused may
     *     carry that kind.
     * @throws DriverException if the commit fails
     * @throws IllegalStateException if {@link #inExternalTransaction()} is {@code true}; optional
     */
    void commit();

    /**
     * Rolls back the transaction {@link #begin()} started.
     *
     * @implSpec After this call the session may {@link #begin()} again.
     * @throws DriverException if the rollback fails
     * @throws IllegalStateException if {@link #inExternalTransaction()} is {@code true}; optional
     */
    void rollback();

    /**
     * Creates a savepoint inside the current transaction.
     *
     * @implSpec Must work without {@link #begin()} when {@link #inExternalTransaction()} is
     *     {@code true}.
     * @param name the savepoint name, never {@code null}, matching
     *     {@code [A-Za-z_][A-Za-z0-9_]{0,29}} and unique within the session
     * @throws DriverException if the savepoint cannot be created
     * @throws IllegalArgumentException if {@code name} does not match the pattern; optional
     */
    void savepoint(String name);

    /**
     * Rolls back to a savepoint created earlier in the current transaction.
     *
     * @implSpec The savepoint must remain usable afterwards: it can be rolled back to again or
     *     released. Must work without {@link #begin()} when {@link #inExternalTransaction()} is
     *     {@code true}.
     * @param name the savepoint name, never {@code null}, matching
     *     {@code [A-Za-z_][A-Za-z0-9_]{0,29}}
     * @throws DriverException if the rollback fails
     * @throws IllegalArgumentException if {@code name} does not match the pattern; optional
     */
    void rollbackToSavepoint(String name);

    /**
     * Releases a savepoint without ending the transaction.
     *
     * @implSpec The core calls this only when {@link Driver#info()} reports
     *     {@link DriverCapability#SAVEPOINT_RELEASE}; a driver that does not report it may throw
     *     {@link UnsupportedOperationException}. Must work without {@link #begin()} when
     *     {@link #inExternalTransaction()} is {@code true}.
     * @param name the savepoint name, never {@code null}, matching
     *     {@code [A-Za-z_][A-Za-z0-9_]{0,29}}
     * @throws DriverException if the release fails
     * @throws IllegalArgumentException if {@code name} does not match the pattern; optional
     * @throws UnsupportedOperationException if the driver does not report
     *     {@link DriverCapability#SAVEPOINT_RELEASE}; optional
     */
    void releaseSavepoint(String name);

    /**
     * Ends any open transaction, restores the connection state and gives the connection back.
     *
     * @implSpec If a transaction started by {@link #begin()} is still open, this method rolls it
     *     back and never commits it. It must be idempotent: a second call does nothing. It must be
     *     valid after any failure of {@link #begin()}, {@link #commit()}, {@link #rollback()} or a
     *     statement. Restoring the connection state and giving the connection back are each
     *     attempted even if an earlier step failed; the first failure is thrown as a
     *     {@link DriverException} and later ones are attached to it with
     *     {@link Throwable#addSuppressed(Throwable)}.
     * @throws DriverException if rolling back, restoring or giving back the connection fails
     */
    @Override
    void close();

    /**
     * Gives the connection back so that it is never handed out again.
     *
     * <p>The core calls this instead of {@link #close()} when the session may be left in a state
     * the next user must not inherit, such as a setting it changed and could not restore.
     *
     * @implSpec The default calls {@link #close()}. A driver over a pool should make the pool drop
     *     the connection. It must be idempotent, and a call after {@link #close()} does nothing.
     * @throws DriverException if giving back the connection fails
     */
    default void discard() {
        close();
    }
}
